    /// A subschema that states a cross-field REQUIREMENT and nothing
    /// else: `required`, optionally with a bare type pin on each field it
    /// names. The "name or id" alternative every model reference carries
    /// is written this way — the type pin is there because `required` in
    /// JSON Schema is satisfied by a key whose value is `null`, and the
    /// id fields accept `null`.
    ///
    /// ReDoc renders no tab for such a branch and it defines no property
    /// of its own, so the title and description guards below skip it —
    /// exactly as they already skip `if`/`then`/`else`.
    fn is_requiredness_constraint(node: &serde_json::Value) -> bool {
        let Some(map) = node.as_object() else {
            return false;
        };
        if !map.contains_key("required")
            || !map
                .keys()
                .all(|k| matches!(k.as_str(), "required" | "properties"))
        {
            return false;
        }
        let Some(serde_json::Value::Object(properties)) = map.get("properties") else {
            return true;
        };
        properties.values().all(|p| {
            p.as_object()
                .is_some_and(|o| o.len() == 1 && o.contains_key("type"))
        })
    }

    fn collect_missing_property_descriptions(
        value: &serde_json::Value,
        path: String,
        missing: &mut Vec<String>,
    ) {
        if is_requiredness_constraint(value) {
            return;
        }
        match value {
            serde_json::Value::Object(map) => {
                if map.get("type").is_some_and(|kind| kind == "object")
                    || map.contains_key("properties")
                {
                    if let Some(serde_json::Value::Object(properties)) = map.get("properties") {
                        for (name, property) in properties {
                            if property.get("description").is_none() {
                                missing.push(format!("{path}/properties/{name}"));
                            }
                        }
                    }
                }

                for (key, child) in map {
                    // `if`/`then`/`else` are cross-field constraint subschemas
                    // (e.g. object_store's cloud-identity rule), not ReDoc-
                    // rendered property definitions, so their inner properties
                    // need no descriptions.
                    if matches!(key.as_str(), "if" | "then" | "else") {
                        continue;
                    }
                    collect_missing_property_descriptions(child, format!("{path}/{key}"), missing);
                }
            }
            serde_json::Value::Array(items) => {
                for (index, child) in items.iter().enumerate() {
                    collect_missing_property_descriptions(
                        child,
                        format!("{path}/{index}"),
                        missing,
                    );
                }
            }
            _ => {}
        }
    }

    fn collect_ref_sibling_metadata(
        value: &serde_json::Value,
        path: String,
        hits: &mut Vec<String>,
    ) {
        match value {
            serde_json::Value::Object(map) => {
                if map.get("$ref").is_some()
                    && map.keys().any(|key| {
                        matches!(
                            key.as_str(),
                            "description" | "default" | "example" | "examples" | "title"
                        )
                    })
                {
                    hits.push(path.clone());
                }

                for (key, child) in map {
                    collect_ref_sibling_metadata(child, format!("{path}/{key}"), hits);
                }
            }
            serde_json::Value::Array(items) => {
                for (index, child) in items.iter().enumerate() {
                    collect_ref_sibling_metadata(child, format!("{path}/{index}"), hits);
                }
            }
            _ => {}
        }
    }

    fn collect_nullable_any_of(value: &serde_json::Value, path: String, hits: &mut Vec<String>) {
        match value {
            serde_json::Value::Object(map) => {
                if let Some(serde_json::Value::Array(variants)) = map.get("anyOf") {
                    if variants.iter().any(|variant| variant["type"] == "null") {
                        hits.push(path.clone());
                    }
                }

                for (key, child) in map {
                    collect_nullable_any_of(child, format!("{path}/{key}"), hits);
                }
            }
            serde_json::Value::Array(items) => {
                for (index, child) in items.iter().enumerate() {
                    collect_nullable_any_of(child, format!("{path}/{index}"), hits);
                }
            }
            _ => {}
        }
    }

    fn collect_redundant_single_ref_all_of(
        value: &serde_json::Value,
        path: String,
        hits: &mut Vec<String>,
    ) {
        match value {
            serde_json::Value::Object(map) => {
                if let Some(serde_json::Value::Array(variants)) = map.get("allOf") {
                    if map.len() == 1 && variants.len() == 1 && variants[0]["$ref"].is_string() {
                        hits.push(path.clone());
                    }
                }

                for (key, child) in map {
                    collect_redundant_single_ref_all_of(child, format!("{path}/{key}"), hits);
                }
            }
            serde_json::Value::Array(items) => {
                for (index, child) in items.iter().enumerate() {
                    collect_redundant_single_ref_all_of(child, format!("{path}/{index}"), hits);
                }
            }
            _ => {}
        }
    }

    fn collect_untitled_schema_variants(
        value: &serde_json::Value,
        path: String,
        missing: &mut Vec<String>,
    ) {
        match value {
            serde_json::Value::Object(map) => {
                for key in ["oneOf", "anyOf"] {
                    if let Some(serde_json::Value::Array(variants)) = map.get(key) {
                        for (index, variant) in variants.iter().enumerate() {
                            // A cross-field requirement is not a shape a
                            // reader picks between, so ReDoc gives it no
                            // tab and a title on it would name something
                            // nobody sees. Same exemption the `not`
                            // subschemas get below.
                            if is_requiredness_constraint(variant) {
                                continue;
                            }
                            if variant["title"].as_str().is_none_or(str::is_empty) {
                                missing.push(format!("{path}/{key}/{index}"));
                            }
                        }
                    }
                }

                for (key, child) in map {
                    // `not` subschemas are negative constraints (e.g. Model's
                    // direct/routing/ensemble mutual exclusion), never rendered
                    // as ReDoc tabs, so their inner variants need no titles.
                    if key == "not" {
                        continue;
                    }
                    collect_untitled_schema_variants(child, format!("{path}/{key}"), missing);
                }
            }
            serde_json::Value::Array(items) => {
                for (index, child) in items.iter().enumerate() {
                    collect_untitled_schema_variants(child, format!("{path}/{index}"), missing);
                }
            }
            _ => {}
        }
    }

